let estado = "Retrasado";

if (estado === "Programado") {
  console.log("Vuelo programado");
} else if (estado === "En vuelo") {
  console.log("Vuelo en ruta");
} else if (estado === "Aterrizado") {
  console.log("Vuelo aterrizó");
} else if (estado === "Retrasado") {
  console.log("Vuelo retrasado");
} else {
  console.log("Estado desconocido");
}
